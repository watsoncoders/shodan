#!/usr/bin/env python3
"""
geoip_enrich_csv.py
----------------------
Enrich the results of a network scan with geographical information from MaxMind's GeoLite2 databases.

Usage:
    python3 geoip_enrich_csv.py csv_file db_file_country db_file_location db_file_asn

where `csv_file` is the input CSV file containing open ports (as generated by masscan_stream_csv.py), and `db_file_country`, `db_file_location`, and `db_file_asn` are the paths to the MaxMind GeoLite2 MMDB files for country, location, and ASN information, respectively.

The script reads each row, looks up the corresponding IP address in the GeoLite2 databases, and appends the following columns to the CSV:

- country\_name: Country name of the IP address
- region\_name, city\_name, zip\_code: Location information of the IP address
- asn\_name, asn\_number: ASN information of the IP address

Notes:
- The script requires the `pygeoip` library to be installed (use `pip install pygeoip`).
- The GeoLite2 MMDB files must be in the correct format and up to date (download from https://dev.maxmind.com/geoip/geoip2/geolite2/).
- Each geolocation lookup runs in a separate process to avoid waiting for previous results.

Example:
    python3 geoip_enrich_csv.py results.csv /path/to/GeoLite2-Country.mmdb /path/to/GeoLite2-City.mmdb /path/to/GeoLite2-ASN.mmdb

The script will create a new CSV file with the original columns plus the new ones:
    geoip_enriched_results.csv
"""

import csv
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Tuple

CSV_FILE = "results.csv"
GEOIP_COUNTRY_DB = "GeoLite2-Country.mmdb"
GEOIP_LOCATION_DB = "GeoLite2-City.mmdb"
GEOIP_ASN_DB = "GeoLite2-ASN.mmdb"


def parse_geoip_output(output: str) -> Dict[str, Any]:
    result = {}
    if output.startswith("GeoLite2 Response"):
        fields = output.split(",")
        if "country" in fields:
            result["country_name"] = fields[fields.index("country")]
        if "region" in fields:
            result["region_name"] = fields[fields.index("region")]
        if "city" in fields:
            result["city_name"] = fields[fields.index("city")]
        if "postal_code" in fields:
            result["zip_code"] = fields[fields.index("postal_code")]
        if "time_zone" in fields:
            result["time_zone"] = fields[fields.index("time_zone")]
    return result


def parse_geoipasn_output(output: str) -> Dict[str, Any]:
    result = {}
    if output.startswith("GeoLite2 ASN Response"):
        fields = output.split(",")
        if "name" in fields:
            result["asn_name"] = fields[fields.index("name")]
        if "number" in fields:
            result["asn_number"] = fields[fields.index("number")]
    return result


def run_geoip_country(ip: str) -> str:
    """Run pygeoip against the given IP address and return the raw output."""
    cmd = ["pygeoip-geolite2", "country", ip, "-f", GEOIP_COUNTRY_DB]
    geoip_country = subprocess.Popen(cmd, stdout=subprocess.PIPE)
    output, _ = geoip_country.communicate()
    return output.decode("utf-8")


def run_geoip_location(ip: str) -> str:
    """Run pygeoip against the given IP address and return the raw output."""
    cmd = ["pygeoip-geolite2", "location", ip, "-f", GEOIP_LOCATION_DB]
    geoip_location = subprocess.Popen(cmd, stdout=subprocess.PIPE)
    output, _ = geoip_location.communicate()
    return output.decode("utf-8")


def run_geoip_asn(ip: str) -> str:
    """Run pygeoip against the given IP address and return the raw output."""
    cmd = ["pygeoip-geolite2", "asn", ip, "-f", GEOIP_ASN_DB]
    geoip_asn = subprocess.Popen(cmd, stdout=subprocess.PIPE)
    output, _ = geoip_asn.communicate()
    return output.decode("utf-8")


def format_row(row: List[str], enriched_data: Dict[str, Any]) -> Tuple[str, ...]:
    return (
        row[0],
        row[1],
        row[2],
        row[3],
        row[4],
        row[5],
        row[6],
        row[7],
        row[8],
        row[9],
        row[10],
        row[11],
        row[12],
        row[13],
        row[14],
        row[15],
        enriched_data.get("country_name"),
        enriched_data.get("region_name"),
        enriched_data.get("city_name"),
        enriched_data.get("zip_code"),
        enriched_data.get("time_zone"),
        enriched_data.get("asn_name"),
        enriched_data.get("asn_number"),
    )


def write_csv(row: Tuple[str, ...], csv_file: Path) -> None:
    """Write a single row to the CSV file and handle any errors."""
    try:
        with csv_file.open("a", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(row)
    except Exception as e:
        print(f"Error writing to CSV: {e}")



def main() -> None:
    if len(sys.argv) < 4:
        print("Usage: python3 geoip_enrich_csv.py csv_file db_file_country db_file_location db_file_asn")
        sys.exit(1)
    csv_file = Path(sys.argv[1])
    db_file_country = Path(sys.argv[2])
    db_file_location = Path(sys.argv[3])
    db_file_asn = Path(sys.argv[4])

    if not csv_file.is_file():
        print(f"Error: {csv_file} not found")
        sys.exit(1)
    if not db_file_country.is_file():
        print(f"Error: {db_file_country} not found")
        sys.exit(1)
    if not db_file_location.is_file():
        print(f"Error: {db_file_location} not found")
        sys.exit(1)
    if not db_file_asn.is_file():
        print(f"Error: {db_file_asn} not found")
        sys.exit(1)

    with csv_file.open() as f:
        reader = csv.reader(f)
        headers = next(reader)
        enriched_headers = headers + [
            "country_name",
            "region_name",
            "city_name",
            "zip_code",
            "time_zone",
            "asn_name",
            "asn_number",
        ]
        with Path("geoip_enriched_results.csv").open("w", newline="") as out_f:
            writer = csv.writer(out_f)
            writer.writerow(enriched_headers)

        for row in reader:
            ip = row[0]
            print(f"Running geolocation lookup for {ip}")
            geoip_country_output = run_geoip_country(ip)
            geoip_location_output = run_geoip_location(ip)
            geoip_asn_output = run_geoip_asn(ip)
            geoip_country_data = parse_geoip_output(geoip_country_output)
            geoip_location_data = parse_geoip_output(geoip_location_output)
            geoip_asn_data = parse_geoipasn_output(geoip_asn_output)
            enriched_data = {**geoip_country_data, **geoip_location_data, **geoip_asn_data}
            enriched_row = format_row(row, enriched_data)
            write_csv(enriched_row, Path("geoip_enriched_results.csv"))


if __name__ == "__main__":
    main()
