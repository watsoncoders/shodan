#!/usr/bin/env python3
"""
nmap_enrich_csv.py
----------------------
Enrich the results of a network scan with additional information from nmap.

Usage:
    python3 nmap_enrich_csv.py csv_file

where `csv_file` is the input CSV file containing open ports (as generated by masscan_stream_csv.py).

The script reads each row, runs nmap against the corresponding IP address, and appends the following columns to the CSV:

- nmap\_version: Nmap version used for the scan
- os\_type, os\_name, os\_version, os\_cpe: OS information from the nmap scan
- tcp\_open\_ports, tcp\_closed\_ports, tcp\_filtered\_ports: Port information from the nmap scan

Notes:
- The script requires nmap to be installed and in the system's PATH.
- The nmap scan runs with default options and no timeout, so it may take a while for large networks.
- Each nmap scan runs in a separate process to avoid waiting for previous results.

Example:
    python3 nmap_enrich_csv.py results.csv

The script will create a new CSV file with the original columns plus the new ones:
    nmap_enrich_results.csv
"""

import csv
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Tuple

CSV_FILE = "results.csv"
NMAP_ENRICHED_CSV_FILE = "nmap_enriched_results.csv"


def parse_nmap_output(output: str) -> Dict[str, Any]:
    result = {}
    for line in output.split("\n"):
        if not line:
            continue
        if line.startswith("Nmap "):
            result["nmap_version"] = line.split("Nmap")[1].strip()
        elif line.startswith("Aggressive OS guesses:"):
            result["os_type"] = None
            result["os_name"] = None
            result["os_version"] = None
            result["os_cpe"] = None
            for guess in line[len("Aggressive OS guesses:"):].strip().split(")"):
                if not guess:
                    continue
                type, name, version, cpe = guess.split(" (")
                result["os_type"] = type
                result["os_name"] = name
                result["os_version"] = version
                result["os_cpe"] = cpe
        elif line.startswith("PORT STATE SERVICE VERSION"):
            result["tcp_open_ports"], result["tcp_closed_ports"], result["tcp_filtered_ports"] = [], [], []
            for port_line in output.split("\n")[1:]:
                if not port_line:
                    continue
                ip, port, state, service, version = port_line.split(",")
                if state == "open":
                    result["tcp_open_ports"].append((port, service, version))
                elif state == "closed":
                    result["tcp_closed_ports"].append((port, service, version))
                elif state == "filtered":
                    result["tcp_filtered_ports"].append((port, service, version))
    return result


def run_nmap(ip: str) -> str:
    """Run nmap against the given IP address and return the raw output."""
    cmd = ["nmap", ip]
    nmap = subprocess.Popen(cmd, stdout=subprocess.PIPE)
    output, _ = nmap.communicate()
    return output.decode("utf-8")


def format_row(row: List[str], enriched_data: Dict[str, Any]) -> Tuple[str, ...]:
    return (
        row[0],
        row[1],
        row[2],
        row[3],
        row[4],
        row[5],
        row[6],
        enriched_data.get("nmap_version"),
        enriched_data.get("os_type"),
        enriched_data.get("os_name"),
        enriched_data.get("os_version"),
        enriched_data.get("os_cpe"),
        enriched_data.get("tcp_open_ports"),
        enriched_data.get("tcp_closed_ports"),
        enriched_data.get("tcp_filtered_ports"),
    )


def write_csv(row: Tuple[str, ...], csv_file: Path) -> None:
    """Write a single row to the CSV file and handle any errors."""
    try:
        with csv_file.open("a", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(row)
    except Exception as e:
        print(f"Error writing to CSV: {e}")



def main() -> None:
    if len(sys.argv) < 2:
        print("Usage: python3 nmap_enrich_csv.py csv_file")
        sys.exit(1)
    csv_file = Path(sys.argv[1])

    if not csv_file.is_file():
        print(f"Error: {csv_file} not found")
        sys.exit(1)

    with csv_file.open() as f:
        reader = csv.reader(f)
        headers = next(reader)
        enriched_headers = headers + [
            "nmap_version",
            "os_type",
            "os_name",
            "os_version",
            "os_cpe",
            "tcp_open_ports",
            "tcp_closed_ports",
            "tcp_filtered_ports",
        ]
        with Path(NMAP_ENRICHED_CSV_FILE).open("w", newline="") as out_f:
            writer = csv.writer(out_f)
            writer.writerow(enriched_headers)

        for row in reader:
            ip = row[0]
            print(f"Running nmap for {ip}")
            nmap_output = run_nmap(ip)
            enriched_data = parse_nmap_output(nmap_output)
            enriched_row = format_row(row, enriched_data)
            write_csv(enriched_row, Path(NMAP_ENRICHED_CSV_FILE))


if __name__ == "__main__":
    main()
